async function qrCommand(sock, chatId, message, input, qrLibrary) {
    const value = String(input || '').trim();
    if (!value) {
        await sock.sendMessage(chatId, { text: 'Usage: .qr <text or link>\nExample: .qr https://example.com' }, { quoted: message });
        return;
    }
    if (value.length > 1400) {
        await sock.sendMessage(chatId, { text: 'QR input is too long. Please keep it under 1,400 characters.' }, { quoted: message });
        return;
    }

    try {
        const qrcode = qrLibrary || require('qrcode');
        const image = await qrcode.toBuffer(value, {
            type: 'png',
            width: 512,
            margin: 2,
            errorCorrectionLevel: 'M'
        });
        if (!Buffer.isBuffer(image) || image.length === 0) throw new Error('QR encoder returned no image.');
        await sock.sendMessage(chatId, {
            image,
            caption: 'QR code generated by DLORD FARHAN.'
        }, { quoted: message });
    } catch (error) {
        console.error('[qr] QR generation failed:', error?.message || error);
        await sock.sendMessage(chatId, { text: 'I could not generate that QR code. Please try a shorter text or reinstall the bot dependencies.' }, { quoted: message });
    }
}

module.exports = { qrCommand };
